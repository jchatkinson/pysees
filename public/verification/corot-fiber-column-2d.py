ops.section('Fiber', 1)
ops.patch('rect', 1, 10, 6, -0.2, -0.2, 0.2, 0.2)
ops.fiber(-0.15000000000000002, -0.15000000000000002, 0.0005, 2)
ops.fiber(-0.15000000000000002, 0.15000000000000002, 0.0005, 2)
ops.fiber(0.15000000000000002, -0.15000000000000002, 0.0005, 2)
ops.fiber(0.15000000000000002, 0.15000000000000002, 0.0005, 2)
