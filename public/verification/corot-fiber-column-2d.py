import openseespy.opensees as ops

ops.wipe()
ops.model('basic', '-ndm', 2, '-ndf', 3)
ops.node(1, 0, 0)
ops.node(2, 0, 0.75)
ops.node(3, 0, 1.5)
ops.node(4, 0, 2.25)
ops.node(5, 0, 3)
