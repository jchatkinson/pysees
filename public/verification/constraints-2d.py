import openseespy.opensees as ops

ops.wipe()
ops.model('basic', '-ndm', 2, '-ndf', 3)
ops.node(1, 0, 0)
ops.node(2, 0, 3)
ops.node(3, 4, 0)
ops.node(4, 4, 3)
ops.node(5, 0.5, 3.5)
ops.node(6, 8, 0)
ops.node(7, 8, 3)
ops.geomTransf('Linear', 1)
ops.element('elasticBeamColumn', 1, 1, 2, 0.01, 200000000000, 0.0001, 1)
ops.element('elasticBeamColumn', 2, 3, 4, 0.01, 200000000000, 0.0002, 1)
ops.element('elasticBeamColumn', 3, 6, 7, 0.01, 200000000000, 0.00030000000000000003, 1)
ops.equalDOF(2, 4, 1)
ops.rigidLink('beam', 2, 5)
ops.equalDOF_Mixed(2, 7, 1, 2, 1)
ops.fix(1, 1, 1, 1)
ops.fix(3, 1, 1, 1)
ops.fix(6, 1, 1, 1)
ops.timeSeries('Linear', 1, '-factor', 1)
ops.recorder('Node', '-file', 'out/disp.out', '-time', '-node', 1, 2, 3, 4, 5, 6, 7, '-dof', 1, 2, 3, 'disp')
ops.recorder('Node', '-file', 'out/reaction.out', '-time', '-node', 1, 2, 3, 4, 5, 6, 7, '-dof', 1, 2, 3, 'reaction')
ops.recorder('Element', '-file', 'out/eleLocalForce.out', '-time', '-ele', 1, 2, 3, 'localForce')
ops.pattern('Plain', 1, 1, '-fact', 1)
ops.load(5, 20000, -500000, 1000)
ops.load(4, 0, -100000, 0)
ops.constraints('Transformation')
ops.numberer('RCM')
ops.system('BandGeneral')
ops.test('NormDispIncr', 0.000001, 25)
ops.algorithm('Newton')
ops.integrator('LoadControl', 0.5)
ops.analysis('Static')
ops.analyze(2)
ops.loadConst('-time', 0)
