/// <reference types="node" />
import { mkdirSync, writeFileSync } from 'node:fs'
import { describe, expect, it } from 'vitest'
import { serializeProject } from '@/app/lib/project/serialize'
import { captureProject } from '@/app/lib/project/types'
import { DEFAULT_PLOT_VIEW } from '@/app/types/plotView'
import { DEFAULT_RESULTS_VIEW } from '@/app/types/resultsView'
import { SRC } from '../helpers'
import type { PlotSpec } from '../types'
import { verifyCase } from '../verify'
import { TRANSFER_SLAB, transferSlab } from './transferSlab'

/**
 * The transfer slab ETABS comparison: runs it in Carapace and OpenSees, checks they agree and that the reactions balance the load, and prints the
 * support reactions. `WRITE=1` also writes the PySees project, the OpenSeesPy script and the reaction table to `docs/etabs/transfer-slab/`.
 */
const DOFS = ['Fx', 'Fy', 'Fz', 'Mx', 'My', 'Mz']
const OUT = 'docs/etabs/transfer-slab'

function solve(mesh: number, footprint: boolean, h: number) {
  const built = transferSlab(mesh, { footprint, h })
  // The slab node at each column head: the top of C1–C4, the base of the transfer column.
  const heads = [1, 2, 3, 4, 5].map((e) => built.model.elements.get(e)!.nodes[e < 5 ? 1 : 0])
  const signal = (q: 'reaction' | 'disp', nodes: number[]) => nodes.flatMap((node) => DOFS.map((d, i): PlotSpec => ({ title: `${q} ${node} ${d}`, x: { q: 'step' }, y: { q, node, dof: i + 1 }, xLabel: '', yLabel: '' })))
  const plots = [...signal('reaction', built.bases), ...signal('disp', heads)]
  const run = verifyCase({ id: `transfer-slab-${mesh}`, category: 'shells', build: () => built, plots, shot: { view: '3d', result: 'deformed' }, sources: [SRC.shell4, SRC.elastic] })
  const value = (k: 'carapace' | 'opensees', from: number, count: number) => Array.from({ length: count }, (_n, c) => DOFS.map((_d, i) => run.result.plots[(from + c) * 6 + i][k].at(-1)![1]))
  return { built, run, heads, carapace: value('carapace', 0, 4), opensees: value('opensees', 0, 4), joints: value('carapace', 4, 5) }
}

const fmt = (v: number, d: number) => (Math.abs(v) < 5e-4 ? '0' : v.toFixed(d))
const sci = (v: number) => (Math.abs(v) < 1e-12 ? '0' : v.toExponential(3))
function jointTable(mesh: number, d: number[][], coords: number[][]) {
  const names = ['C1 head', 'C2 head', 'C3 head', 'C4 head', 'TC base']
  return [`Mesh ${mesh} in. Slab joints at the column heads: displacements in, rotations rad.`, '', '| Joint | X, Y (in) | Ux | Uy | Uz | Rx | Ry | Rz |', '|---|---|--:|--:|--:|--:|--:|--:|', ...d.map((v, c) => `| ${names[c]} | ${coords[c][0]}, ${coords[c][1]} | ${v.map(sci).join(' | ')} |`)].join('\n')
}
function table(mesh: number, r: number[][], coords: number[][]) {
  const rows = r.map((v, c) => `| ${c + 1} | (${coords[c][0] / 12}, ${coords[c][1] / 12}) | ${v.slice(0, 3).map((x) => fmt(x, 2)).join(' | ')} | ${v.slice(3).map((x) => fmt(x / 12, 1)).join(' | ')} |`)
  const sum = DOFS.slice(0, 3).map((_d, i) => fmt(r.reduce((a, v) => a + v[i], 0), 2))
  return [`Mesh ${mesh} in. Forces kip, moments kip·ft, about each column base.`, '', '| Column | Base (ft) | Fx | Fy | Fz | Mx | My | Mz |', '|---|---|--:|--:|--:|--:|--:|--:|', ...rows, `| Sum | | ${sum.join(' | ')} | | | |`].join('\n')
}

describe('transfer slab (ETABS comparison)', () => {
  it('agrees with OpenSees, balances the load and writes the reactions', () => {
    const sections: Record<string, string[]> = {}
    for (const h of [36, 12]) for (const variant of ['point', 'footprint'] as const) for (const mesh of [12, 6]) {
      const { built, run, heads, carapace, opensees, joints } = solve(mesh, variant === 'footprint', h)
      const tables = (sections[`${h} ${variant}`] ??= [])
      expect(run.result.problems).toEqual([])
      carapace.forEach((v, c) => v.forEach((x, i) => expect(x).toBeCloseTo(opensees[c][i], 3)))
      expect(carapace.reduce((a, v) => a + v[2], 0)).toBeCloseTo(TRANSFER_SLAB.load, 2)
      const coords = built.bases.map((n) => built.model.nodes.get(n)!.coords)
      tables.push(table(mesh, carapace, coords), jointTable(mesh, joints, heads.map((n) => built.model.nodes.get(n)!.coords)))
      const file = `${OUT}/transfer-slab${h === 36 ? '' : `-${h}in`}${variant === 'footprint' ? '-footprint' : ''}`
      if (process.env.WRITE && mesh === 12) {
        mkdirSync(OUT, { recursive: true })
        writeFileSync(`${file}.py`, run.script)
        const doc = captureProject({
          model: built.model, analysisHistory: built.history, gridlines: built.gridlines ?? [], levels: built.levels ?? [], nextGridlineId: 5, nextLevelId: 4,
          savedPlots: [], nextSavedPlotId: 1, activeSavedPlotId: null, viewSettings: {}, unitPrefs: { length: 'ft' }, hiddenLoadPatterns: [], resultsView: DEFAULT_RESULTS_VIEW, plotView: DEFAULT_PLOT_VIEW,
        })
        writeFileSync(`${file}.pysees.py`, serializeProject(doc))
      }
    }
    const md = `<!-- Generated by WRITE=1 npx vitest run src/app/lib/verification/etabs -->\n# Transfer slab: PySees (Carapace) results\n\nOpenSeesPy agrees with these to solver precision.\n\n${[36, 12].map((h) => `## ${h} in slab, point connection (each column on one slab node)\n\n${sections[`${h} point`].join('\n\n')}\n\n## ${h} in slab, rigid footprint (each column head tied by rigid links to the slab nodes in its 24 × 24 in footprint)\n\n${sections[`${h} footprint`].join('\n\n')}\n`).join('\n')}`
    console.log(md)
    if (process.env.WRITE) writeFileSync(`${OUT}/reactions.md`, md)
  }, 120_000)
})
