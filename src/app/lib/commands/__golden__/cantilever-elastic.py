import openseespy.opensees as ops

ops.wipe()
ops.model('basic', '-ndm', 2, '-ndf', 3)
ops.node(1, 0, 0)
ops.node(2, 0, 0.75)
ops.node(3, 0, 1.5)
ops.node(4, 0, 2.25)
ops.node(5, 0, 3)
ops.mass(2, 250, 250, 0)
ops.mass(3, 250, 250, 0)
ops.mass(4, 250, 250, 0)
ops.mass(5, 125, 125, 0)
ops.uniaxialMaterial('Elastic', 1, 200000000000)
ops.geomTransf('Linear', 1)
ops.element('elasticBeamColumn', 1, 1, 2, 0.01, 200000000000, 0.0001, 1)
ops.element('elasticBeamColumn', 2, 2, 3, 0.01, 200000000000, 0.0001, 1)
ops.element('elasticBeamColumn', 3, 3, 4, 0.01, 200000000000, 0.0001, 1)
ops.element('elasticBeamColumn', 4, 4, 5, 0.01, 200000000000, 0.0001, 1)
ops.fix(1, 1, 1, 1)
ops.timeSeries('Linear', 1, '-factor', 1)
ops.recorder('Node', '-file', 'out/disp.out', '-time', '-node', 1, 2, 3, 4, 5, '-dof', 1, 2, 3, 'disp')
ops.recorder('Node', '-file', 'out/reaction.out', '-time', '-node', 1, 2, 3, 4, 5, '-dof', 1, 2, 3, 'reaction')
ops.recorder('Element', '-file', 'out/eleLocalForce.out', '-time', '-ele', 1, 2, 3, 4, 'localForce')
ops.constraints('Plain')
ops.numberer('RCM')
ops.system('BandGeneral')
ops.eigen(3)
ops.pattern('Plain', 1, 1, '-fact', 1)
ops.load(5, 10000, 0, 0)
ops.constraints('Plain')
ops.numberer('RCM')
ops.system('BandGeneral')
ops.test('NormDispIncr', 0.000001, 25)
ops.algorithm('Newton')
ops.integrator('LoadControl', 0.1)
ops.analysis('Static')
ops.analyze(10)
ops.loadConst('-time', 0)
