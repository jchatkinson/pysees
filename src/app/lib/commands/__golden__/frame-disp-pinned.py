import openseespy.opensees as ops

ops.wipe()
ops.model('basic', '-ndm', 2, '-ndf', 3)
ops.node(1, 0, 0)
ops.node(2, 6, 0)
ops.node(3, 0, 3.5)
ops.node(4, 6, 3.5)
ops.mass(3, 2196, 2196, 0)
ops.mass(4, 2196, 2196, 0)
ops.uniaxialMaterial('Steel01', 1, 400000000, 200000000000, 0.01)
ops.uniaxialMaterial('Concrete01', 2, -30000000, -0.002, -6000000, -0.006)
ops.section('Fiber', 1)
ops.patch('rect', 2, 8, 8, -0.2, -0.2, 0.2, 0.2)
ops.fiber(-0.15, -0.15, 0.00031415926535897936, 1)
ops.fiber(-0.15, 0, 0.00031415926535897936, 1)
ops.fiber(-0.15, 0.15, 0.00031415926535897936, 1)
ops.fiber(0, -0.15, 0.00031415926535897936, 1)
ops.fiber(0, 0.15, 0.00031415926535897936, 1)
ops.fiber(0.15, -0.15, 0.00031415926535897936, 1)
ops.fiber(0.15, 0, 0.00031415926535897936, 1)
ops.fiber(0.15, 0.15, 0.00031415926535897936, 1)
ops.geomTransf('Linear', 1)
ops.beamIntegration('Legendre', 1, 1, 4)
ops.element('dispBeamColumn', 1, 1, 3, 1, 1)
ops.element('dispBeamColumn', 2, 2, 4, 1, 1)
ops.element('dispBeamColumn', 3, 3, 4, 1, 1)
ops.fix(1, 1, 1, 0)
ops.fix(2, 1, 1, 0)
ops.timeSeries('Linear', 1, '-factor', 1)
ops.recorder('Node', '-file', 'out/disp.out', '-time', '-node', 1, 2, 3, 4, '-dof', 1, 2, 3, 'disp')
ops.recorder('Node', '-file', 'out/reaction.out', '-time', '-node', 1, 2, 3, 4, '-dof', 1, 2, 3, 'reaction')
ops.recorder('Element', '-file', 'out/eleLocalForce.out', '-time', '-ele', 1, 2, 3, 'localForce')
ops.constraints('Plain')
ops.numberer('RCM')
ops.system('BandGeneral')
ops.eigen(2)
# Dead Load
ops.pattern('Plain', 1, 1, '-fact', 1)
ops.eleLoad('-ele', 3, '-type', '-beamUniform', -7182.045, 0)
# Live Load
ops.pattern('Plain', 2, 1, '-fact', 1)
ops.eleLoad('-ele', 3, '-type', '-beamUniform', -11491.272, 0)
ops.constraints('Plain')
ops.numberer('RCM')
ops.system('BandGeneral')
ops.test('NormDispIncr', 0.000001, 25)
ops.algorithm('Newton')
ops.integrator('LoadControl', 0.1)
ops.analysis('Static')
ops.analyze(10)
ops.loadConst('-time', 0)
# Push
ops.pattern('Plain', 3, 1, '-fact', 1)
ops.load(3, 1000, 0, 0)
ops.load(4, 1000, 0, 0)
ops.constraints('Plain')
ops.numberer('RCM')
ops.system('BandGeneral')
ops.test('NormDispIncr', 0.000001, 25)
ops.algorithm('Newton')
ops.integrator('DisplacementControl', 4, 1, 0.00105)
ops.analysis('Static')
ops.analyze(100)
